#!/usr/bin/env python3
"""2026-09-05: permanently archives every batch run's results into results/
(git-tracked), independent of data/ (gitignored, and the .rrd recordings in
there are large enough that periodic manual cleanup is realistic). Run any
time new batches complete -- safe to re-run, overwrites with current data,
never deletes a tag this project has ever produced (existing results/
subdirectories are left alone even if the matching data/runs/ dir is gone,
so a cleaned-up data/ never causes archived results to vanish).

Does NOT copy .rrd recordings (100s of MB each, visualization only, not
numeric results) or full episode logs -- just batch_metrics.json and the
small early-phase evidence JSON files, which together are the actual
retrievable numbers. Full narrative context (why a run was done, what it
showed) lives in PROGRESS.md's Decisions Log -- this script's job is only
to make sure the raw numbers behind that narrative can never be lost.

Usage: python scripts/archive_results.py
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS_DIR = ROOT / "results" / "batch_runs"
DATA_RUNS = ROOT / "data" / "runs"

# Small non-phase4-batch evidence files worth preserving verbatim (Phase 1-3
# verification-gate artifacts, per CLAUDE.md SS8/SS9 -- these are NOT
# batch_metrics.json but are still real retrievable evidence).
EXTRA_FILES = [
    "phase2_smoke/positions.json",
    "phase2_smoke/push_log.json",
    "phase2_smoke/final_corrections.json",
    "phase2_smoke/updates.json",
    "phase3_replay/memory_diff.json",
    "phase3_replay/replay_results.json",
    "phase4_closed_loop/step_log.json",
]


def copy_batch_metrics():
    n = 0
    for src in sorted(DATA_RUNS.glob("*/batch_metrics.json")):
        tag = src.parent.name
        dst_dir = RESULTS_DIR / tag
        dst_dir.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst_dir / "batch_metrics.json")
        n += 1
    return n


def copy_extra_files():
    n = 0
    for rel in EXTRA_FILES:
        src = DATA_RUNS / rel
        if not src.exists():
            continue
        dst = RESULTS_DIR / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        n += 1
    return n


def build_index():
    rows = []
    for d in sorted(RESULTS_DIR.iterdir()):
        f = d / "batch_metrics.json"
        if not f.exists():
            continue
        m = json.loads(f.read_text())
        flags = []
        if m.get("persistent_across_queries"):
            flags.append("persistent")
        if m.get("vqa_verification"):
            flags.append("vqa")
        if m.get("coverage_memory_enabled") is False:
            flags.append("no-coverage-mem")
        if m.get("theta_direct_used") is not None:
            flags.append(f"theta={m['theta_direct_used']}")
        if m.get("min_confirming_observations") is not None:
            flags.append(f"minconf={m['min_confirming_observations']}")
        rows.append({
            "tag": d.name,
            "n_episodes": m.get("n_episodes"),
            "success_rate": m.get("success_rate"),
            "mean_spl": m.get("mean_spl"),
            "flags": ",".join(flags) if flags else "-",
            "scene": (m.get("scene_path") or "").split("/")[-1] or "-",
        })
    return rows


def write_index_md(rows):
    lines = [
        "# Archived batch results -- index",
        "",
        "Auto-generated by `scripts/archive_results.py` -- do not hand-edit,",
        "re-run the script instead (it regenerates this file from the archived",
        "`batch_metrics.json` files, which are the actual source of truth).",
        "",
        "Every row's full JSON (all episodes, branch counts, verification",
        "detail, etc.) is at `results/batch_runs/<tag>/batch_metrics.json`.",
        "For WHY a run was done and what it showed, see `PROGRESS.md`'s",
        "Decisions Log (search for the tag name or the date) -- this index is",
        "just fast numeric lookup, not the narrative record.",
        "",
        "| tag | n | success_rate | mean_spl | flags | scene |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        sr = f"{r['success_rate']:.3f}" if r['success_rate'] is not None else "-"
        spl = f"{r['mean_spl']:.4f}" if r['mean_spl'] is not None else "-"
        lines.append(f"| {r['tag']} | {r['n_episodes']} | {sr} | {spl} | {r['flags']} | {r['scene']} |")
    (ROOT / "results" / "INDEX.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    n_batch = copy_batch_metrics()
    n_extra = copy_extra_files()
    rows = build_index()
    write_index_md(rows)
    print(f"archived {n_batch} batch_metrics.json + {n_extra} early-phase evidence files")
    print(f"index: results/INDEX.md ({len(rows)} rows)")
